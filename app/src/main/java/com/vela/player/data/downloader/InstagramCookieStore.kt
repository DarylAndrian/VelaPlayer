package com.vela.player.data.downloader

import android.content.Context
import android.webkit.CookieManager
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

/**
 * Persists Instagram WebView session cookies in app-private internal storage
 * formatted as a Netscape cookies.txt file for yt-dlp and as a Cookie header for OkHttp.
 */
class InstagramCookieStore(private val context: Context) {

    private val cookieDir: File
        get() = File(context.filesDir, "cookies").apply { if (!exists()) mkdirs() }

    val cookieFile: File
        get() = File(cookieDir, "ig_cookies.txt")

    fun hasValidSession(): Boolean {
        val raw = readWebViewCookieHeader()
        if (raw.contains("sessionid=")) return true
        return cookieFile.exists() && cookieFile.readText().contains("sessionid")
    }

    fun readWebViewCookieHeader(): String {
        val manager = CookieManager.getInstance()
        val parts = listOf(
            manager.getCookie("https://www.instagram.com"),
            manager.getCookie("https://instagram.com")
        ).filterNotNull().filter { it.isNotBlank() }

        val merged = linkedMapOf<String, String>()
        for (raw in parts) {
            raw.split(";").forEach { pair ->
                val idx = pair.indexOf('=')
                if (idx > 0) {
                    val key = pair.substring(0, idx).trim()
                    val value = pair.substring(idx + 1).trim()
                    if (key.isNotEmpty()) merged[key] = value
                }
            }
        }
        return merged.entries.joinToString("; ") { "${it.key}=${it.value}" }
    }

    /**
     * Exports current Android WebView Instagram cookies to Netscape cookies.txt.
     * Returns true if an authenticated `sessionid` cookie was found and saved.
     */
    suspend fun syncFromWebView(): Boolean = withContext(Dispatchers.IO) {
        val cookieHeader = readWebViewCookieHeader()
        if (cookieHeader.isBlank() || !cookieHeader.contains("sessionid=")) {
            return@withContext false
        }

        val expiryEpoch = (System.currentTimeMillis() / 1000L) + 60L * 60L * 24L * 90L
        val builder = StringBuilder()
        builder.appendLine("# Netscape HTTP Cookie File")
        builder.appendLine("# Generated by VelaPlayer for local authenticated Instagram downloads")

        cookieHeader.split(";").forEach { pair ->
            val idx = pair.indexOf('=')
            if (idx > 0) {
                val name = pair.substring(0, idx).trim()
                val value = pair.substring(idx + 1).trim()
                if (name.isNotEmpty()) {
                    // domain, includeSubdomains, path, secure, expires, name, value
                    builder.appendLine(".instagram.com\tTRUE\t/\tTRUE\t$expiryEpoch\t$name\t$value")
                }
            }
        }

        cookieFile.writeText(builder.toString())
        true
    }

    fun getCookieHeaderForHttp(): String? {
        val live = readWebViewCookieHeader()
        if (live.contains("sessionid=")) return live
        if (!cookieFile.exists()) return null

        val pairs = cookieFile.readLines()
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .mapNotNull { line ->
                val cols = line.split("\t")
                if (cols.size >= 7) "${cols[5]}=${cols[6]}" else null
            }
        return pairs.takeIf { it.isNotEmpty() }?.joinToString("; ")
    }

    fun getCookieFileIfPresent(): File? =
        cookieFile.takeIf { it.exists() && it.length() > 0L }

    suspend fun clearSession() = withContext(Dispatchers.IO) {
        runCatching {
            val manager = CookieManager.getInstance()
            manager.removeAllCookies(null)
            manager.flush()
        }
        if (cookieFile.exists()) {
            cookieFile.delete()
        }
    }
}
